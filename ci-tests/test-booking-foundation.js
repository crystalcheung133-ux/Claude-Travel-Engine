const fs=require('fs');
const path=require('path');
const root=path.join(__dirname,'..');
const read=f=>fs.readFileSync(path.join(root,f),'utf8');
const runtime=read('bookings-runtime.js');
const authority=read('booking-authority.js');
const tripRuntime=read('trip-runtime.js');
const tripHtml=read('trip.html');
const bookingsHtml=read('bookings.html');
function must(cond,msg){if(!cond){console.error('FAIL:',msg);process.exitCode=1;}else console.log('PASS:',msg);}
must(fs.existsSync(path.join(root,'bookings.html'))&&fs.existsSync(path.join(root,'bookings-runtime.js')),'generic Booking Centre production files exist');
must(/Accommodation','Restaurants','Spa','Activities','Transport/.test(runtime),'Booking Centre has five reusable categories');
must(/CATEGORY_ORDER\.filter\(key=>all\.some/.test(runtime),'empty booking categories are hidden');
must(/==='confirmed'\?'confirmed':'pending'/.test(runtime),'Booking Centre normalizes status to confirmed/pending only');
must(!/cancelled/.test(runtime),'Booking Centre does not retain cancelled as a display status');
must(/function remove\(id,target\)/.test(authority)&&/deletedIds/.test(authority),'Booking Authority supports persistent delete tombstones');
must(/choices:\['pending','confirmed'\]/.test(tripRuntime),'Studio booking status editor exposes Pending/Confirmed only');
must(/Delete Booking/.test(tripRuntime)&&/deleteBookingRecord/.test(tripRuntime),'Studio booking editor supports delete instead of cancelled');
must(/row\[1\].*trim/.test(tripRuntime)&&/if\(!status&&!rows\.length\)return ''/.test(tripRuntime),'blank booking/payment fields do not render');
must(/NAVIGATION\.build\('bookings'\)/.test(tripRuntime),'Trip menu routes booking access through Booking Centre');
must(/id="bookingList"/.test(bookingsHtml)&&/id="bookingSummary"/.test(bookingsHtml),'Booking Centre page has list and summary hosts');
if(!process.exitCode)console.log('BOOKING FOUNDATION: PASS — taxonomy, status, sparse rendering and deletion contracts verified.');
